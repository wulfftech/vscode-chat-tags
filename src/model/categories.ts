import * as vscode from 'vscode';
import { SubtitleMode } from '../core/subtitleText';

// categories and per-session metadata live in globalState, not workspaceState —
// session ids are uuids and unique across workspaces, and empty-window sessions
// don't belong to any workspace at all

const CATEGORIES_KEY = 'chatTags.categories';
const SESSION_META_KEY = 'chatTags.sessionMeta';
const BASELINE_KEY = 'chatTags.baselineAt';

export interface Category {
	id: string;
	name: string;
	// raw hex — inside our own webview there's no registered-colour requirement
	colour: string;
}

export interface SessionMeta {
	categoryId?: string;
	subtitle?: string;
	subtitleSource?: 'manual' | 'llm';
	subtitleUpdatedAt?: number;
	// which kind of line this is, so the automatic sweep regenerates what the session was
	// last given rather than whatever chatTags.subtitleMode happens to say today
	subtitleMode?: SubtitleMode;
	// shown instead of the title in the session file. the file itself is never written —
	// vs code holds it open and appends to it, so our record would be clobbered or worse
	title?: string;
	// only 'manual' guards against being regenerated by accident
	titleSource?: 'manual' | 'llm';
	// last time the user actually opened this session — anything newer needs attention
	seenAt?: number;
	// archived is ours, not vs code's. its own archived state lives in state.vscdb behind
	// the storage service, so we could write it but never read it back to reconcile
	archivedAt?: number;
}

